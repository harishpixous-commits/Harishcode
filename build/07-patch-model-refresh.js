const fs = require('fs');

const file = 'tmp/hc-src/out/renderer/index.html';
let html = fs.readFileSync(file, 'utf8');

const START = '<!-- harish-code-brand-guard -->';
const END_MARK = '    <script type="module" crossorigin';

const startIdx = html.indexOf(START);
const endIdx = html.indexOf(END_MARK);
if (startIdx < 0 || endIdx < 0 || endIdx < startIdx) {
  console.error('guard block boundaries not found');
  process.exit(1);
}

const lines = [
  '<!-- harish-code-brand-guard -->',
  '    <style>',
  '      .hc-refresh {',
  '        display: inline-flex;',
  '        align-items: center;',
  '        justify-content: center;',
  '        width: 24px;',
  '        height: 24px;',
  '        margin-inline-start: 6px;',
  '        border: 0;',
  '        border-radius: 6px;',
  '        background: transparent;',
  '        color: var(--icon-icon-muted, currentColor);',
  '        cursor: pointer;',
  '        flex: 0 0 auto;',
  '        transition: background-color .12s ease, color .12s ease;',
  '      }',
  '      .hc-refresh:hover {',
  '        background: rgba(128,128,128,.16);',
  '        color: var(--icon-icon-base, currentColor);',
  '      }',
  '      .hc-refresh:active { transform: scale(.94); }',
  '      .hc-refresh svg { width: 14px; height: 14px; display: block; }',
  '      .hc-refresh.hc-spinning svg { animation: hc-spin .7s linear infinite; }',
  '      @keyframes hc-spin { to { transform: rotate(360deg); } }',
  '      @media (prefers-reduced-motion: reduce) {',
  '        .hc-refresh.hc-spinning svg { animation: none; opacity: .5; }',
  '      }',
  '    </style>',
  '    <script>',
  '      ;(function () {',
  '        /* ---- brand wording normaliser ---- */',
  '        var MAP = { "OpenCode": "Harish Code", "opencode": "Harish Code" }',
  '        var BLOCK = { SCRIPT: 1, STYLE: 1, CODE: 1, PRE: 1 }',
  '',
  '        function fixNode(node) {',
  '          var parent = node.parentNode',
  '          if (!parent || BLOCK[parent.nodeName]) return',
  '          var v = node.nodeValue',
  '          if (!v) return',
  '          var t = MAP[v.trim()]',
  '          if (!t) return',
  '          node.nodeValue = v.replace(v.trim(), t)',
  '        }',
  '',
  '        function walk(root) {',
  '          if (!root) return',
  '          if (root.nodeType === 3) { fixNode(root); return }',
  '          if (BLOCK[root.nodeName]) return',
  '          var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null)',
  '          var n, batch = []',
  '          while ((n = walker.nextNode())) batch.push(n)',
  '          for (var i = 0; i < batch.length; i++) fixNode(batch[i])',
  '        }',
  '',
  '        /* ---- model list refresh button ---- */',
  '        var REFRESH_SVG =',
  '          \'<svg viewBox="0 0 16 16" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">\' +',
  '          \'<path d="M13.5 8a5.5 5.5 0 1 1-1.61-3.89" stroke="currentColor" stroke-width="1.5" \' +',
  '          \'stroke-linecap="round"/>\' +',
  '          \'<path d="M13.9 2.4v3.2h-3.2" stroke="currentColor" stroke-width="1.5" \' +',
  '          \'stroke-linecap="round" stroke-linejoin="round"/></svg>\'',
  '',
  '        function serverOrigin() {',
  '          var entries = performance.getEntriesByType("resource")',
  '          for (var i = 0; i < entries.length; i++) {',
  '            try {',
  '              var u = new URL(entries[i].name)',
  '              if (u.hostname === "127.0.0.1" || u.hostname === "localhost") return u.origin',
  '            } catch (e) {}',
  '          }',
  '          return null',
  '        }',
  '',
  '        function refresh(btn) {',
  '          if (btn.dataset.busy === "1") return',
  '          btn.dataset.busy = "1"',
  '          btn.classList.add("hc-spinning")',
  '          var origin = serverOrigin()',
  '          var done = function () { setTimeout(function () { location.reload() }, 300) }',
  '          if (!origin) { done(); return }',
  '          var urls = ["/api/model", "/api/provider"]',
  '          var pending = urls.length',
  '          var finish = function () { if (--pending <= 0) done() }',
  '          urls.forEach(function (p) {',
  '            fetch(origin + p, { cache: "no-store" }).then(finish, finish)',
  '          })',
  '        }',
  '',
  '        function addRefreshButtons() {',
  '          var heads = document.querySelectorAll("h3.settings-models-group-header")',
  '          for (var i = 0; i < heads.length; i++) {',
  '            var h = heads[i]',
  '            if (h.querySelector(".hc-refresh")) continue',
  '            var btn = document.createElement("button")',
  '            btn.type = "button"',
  '            btn.className = "hc-refresh"',
  '            btn.title = "Refresh models"',
  '            btn.setAttribute("aria-label", "Refresh models")',
  '            btn.innerHTML = REFRESH_SVG',
  '            btn.addEventListener("click", function (ev) {',
  '              ev.preventDefault()',
  '              ev.stopPropagation()',
  '              refresh(this)',
  '            })',
  '            h.appendChild(btn)',
  '          }',
  '        }',
  '',
  '        function start() {',
  '          walk(document.body)',
  '          addRefreshButtons()',
  '          new MutationObserver(function (records) {',
  '            for (var i = 0; i < records.length; i++) {',
  '              var r = records[i]',
  '              if (r.type === "characterData") { fixNode(r.target); continue }',
  '              for (var j = 0; j < r.addedNodes.length; j++) walk(r.addedNodes[j])',
  '            }',
  '            addRefreshButtons()',
  '          }).observe(document.body, { childList: true, subtree: true, characterData: true })',
  '        }',
  '',
  '        if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start)',
  '        else start()',
  '      })()',
  '    </script>',
  '',
].join('\n');

html = html.slice(0, startIdx) + lines + html.slice(endIdx);
fs.writeFileSync(file, html, 'utf8');
console.log('refresh button + brand guard written to index.html');
